#!/usr/bin/env python
"""Generate src/descriptors/element_table.rs from RDKit's periodic table.

Usage: python scripts/gen_element_table.py > src/descriptors/element_table.rs

RDKit's data comes from IUPAC/NIST (atomic weights, isotope masses) and the
Blue Obelisk data repository. Regenerate when updating the reference toolkit.
"""

from rdkit import Chem, rdBase

pt = Chem.GetPeriodicTable()

# Radiolabels and tracers that appear in medicinal chemistry files, in addition
# to every naturally occurring isotope.
LABELLED = {
    (1, 3), (6, 11), (6, 14), (7, 13), (8, 15), (9, 18), (15, 32), (15, 33), (16, 35),
    (17, 36), (26, 59), (27, 57), (27, 58), (27, 60), (29, 64), (31, 67), (31, 68),
    (34, 75), (35, 76), (35, 77), (35, 82), (38, 89), (39, 90), (40, 89), (43, 99),
    (49, 111), (53, 123), (53, 124), (53, 125), (53, 131), (71, 177), (81, 201),
    (86, 222), (88, 223), (88, 226), (92, 235), (94, 239),
}

print(f"""//! Periodic table data, generated by `scripts/gen_element_table.py`
//! from RDKit {rdBase.rdkitVersion}. Do not edit by hand.

/// One row per element: (atomic number, symbol, standard atomic weight,
/// most-common-isotope mass, outer-shell electrons, allowed valences,
/// covalent radius in Angstroms).
/// An empty valence list means "any valence" (no implicit hydrogens).
#[allow(clippy::type_complexity)]
pub(crate) static ELEMENT_ROWS: &[(u8, &str, f64, f64, u8, &[u8], f64)] = &[""")
for z in range(1, 119):
    vals = [v for v in pt.GetValenceList(z) if v >= 0]
    vl = "&[" + ", ".join(str(v) for v in vals) + "]"
    print(f"    ({z}, \"{pt.GetElementSymbol(z)}\", {pt.GetAtomicWeight(z)!r}, "
          f"{pt.GetMostCommonIsotopeMass(z)!r}, {pt.GetNOuterElecs(z)}, {vl}, "
          f"{pt.GetRcovalent(z)!r}),")
print("];\n")

print("""/// Isotope masses: (atomic number, mass number, exact mass), sorted.
pub(crate) static ISOTOPE_MASSES: &[(u8, u16, f64)] = &[""")
for z in range(1, 119):
    for a in range(1, 300):
        m = pt.GetMassForIsotope(z, a)
        if m > 0 and (pt.GetAbundanceForIsotope(z, a) > 0 or (z, a) in LABELLED):
            print(f"    ({z}, {a}, {m!r}),")
print("];")
